RenderProgram::RenderProgram(RenderCore& core, const ProgramSnapshot& snapshot)
        : mCore(core),
          mDeviceGeneration(core.deviceGeneration()),
          mSnapshot(std::make_shared<ProgramSnapshot>(snapshot)) {
  backend::Device* device = core.device();
  if (device == nullptr) {
    mDiagnostics = "the render core has no device";
    return;
  }

  const std::shared_ptr<const ProgramSnapshot>& stored = mSnapshot;
  const bool preparedVertex = !stored->desc.vertexSpirv.empty();
  // A `samplerExternalOES` has no SPIR-V equivalent, so an external-texture program must use the direct
  // GLSL path even when the build has shaderc and normally prefers GLSL->SPIR-V. The backend still has to
  // accept direct GLSL; Vulkan does not, and the composition below reports that explicitly.
  const bool externalInput = stored->externalInputMask != 0;
  const bool directCapable = device->getCapabilities().acceptsGlslDirect;
  mDirectGlsl = (acceptsDirectGlsl(*device) || (externalInput && directCapable)) && !preparedVertex;
  mEsDialect = isEsDialect(*device);
  mTopDown = hasTopDownTargets(*device);
  mInputCount = snapshot.desc.inputCount;
  mParamsBinding = mInputCount;
  mExtraBinding = mInputCount + 1;

  ComposedProgramSources sources;
  std::string compositionError;
  if (!composeProgramSources(*stored, mDirectGlsl, mEsDialect, mTopDown, sources, compositionError)) {
    mDiagnostics = std::move(compositionError);
    return;
  }
  mVertexSource = std::move(sources.vertexSource);
  mFragmentSource = std::move(sources.fragmentSource);
  const bool body = sources.body;

  // The binding table. A composed source carries no decorations the compiler can reflect (OpenGL
  // semantics strip them), so the table is stated here; it is also what a later link needs, which is why
  // it is a member rather than a local.
  const uint32_t extraCount = static_cast<uint32_t>(stored->textureNames.size());
  const uint32_t totalBindings = mInputCount + 1 + extraCount;
  if (totalBindings == 0 || totalBindings > backend::kMaxDescriptorBindings) {
    mDiagnostics = "the effect needs " + std::to_string(totalBindings) + " samplers but the backend supports " +
                   std::to_string(backend::kMaxDescriptorBindings);
    return;
  }

  mBindingNames.reserve(totalBindings);
  for (uint32_t index = 0; index < mInputCount; ++index) mBindingNames.push_back("uInput" + std::to_string(index));
  mBindingNames.push_back("uParams");
  for (const std::string& name : stored->textureNames) mBindingNames.push_back(name);

  mSamplerBindings.resize(totalBindings);
  for (uint32_t index = 0; index < totalBindings; ++index) mSamplerBindings[index] = index;

  mDeclarations.resize(totalBindings);
  for (uint32_t index = 0; index < totalBindings; ++index) {
    mDeclarations[index].set = 0;
    mDeclarations[index].binding = index;
    mDeclarations[index].type = backend::BindingType::TextureSampler;
    mDeclarations[index].arraySize = 1;
    mDeclarations[index].name = mBindingNames[index].c_str();
    mDeclarations[index].location = backend::kNoShaderLocation;
  }

  // Compile both stages once, then release the modules: a pipeline links its own modules, because the
  // OpenGL backend consumes a module when it links. What the program keeps is the source.
  backend::ShaderModuleDescriptor vertexDescriptor;
  vertexDescriptor.stage = backend::ShaderStage::Vertex;
  if (preparedVertex) {
    vertexDescriptor.language = backend::ShaderModuleDescriptor::Language::SPIRV;
    vertexDescriptor.code = stored->desc.vertexSpirv.data();
    vertexDescriptor.codeSize = stored->desc.vertexSpirv.size() * sizeof(uint32_t);
  } else {
    vertexDescriptor.language = mDirectGlsl ? backend::ShaderModuleDescriptor::Language::GLSLDirect
                                            : backend::ShaderModuleDescriptor::Language::GLSL;
    vertexDescriptor.code = mVertexSource.c_str();
    vertexDescriptor.codeSize = mDirectGlsl ? mVertexSource.size() : mVertexSource.size() + 1;
  }
  vertexDescriptor.label = "effect/effect.vert";
  backend::ShaderModuleHandle vertexModule = backend::ShaderModuleHandle::invalid();
  if (!backend::isSuccess(device->createShaderModule(vertexDescriptor, &vertexModule))) {
    mDiagnostics = "the effect's vertex stage did not compile";
    return;
  }
  device->destroyShaderModule(vertexModule);

  backend::ShaderModuleDescriptor fragmentDescriptor;
  fragmentDescriptor.stage = backend::ShaderStage::Fragment;
  fragmentDescriptor.label = "effect/effect.frag";
  if (body) {
    fragmentDescriptor.language = mDirectGlsl ? backend::ShaderModuleDescriptor::Language::GLSLDirect
                                              : backend::ShaderModuleDescriptor::Language::GLSL;
    fragmentDescriptor.code = mFragmentSource.c_str();
    fragmentDescriptor.codeSize = mDirectGlsl ? mFragmentSource.size() : mFragmentSource.size() + 1;
    fragmentDescriptor.bindingDeclarations = mDeclarations.data();
    fragmentDescriptor.bindingDeclarationCount = static_cast<uint32_t>(mDeclarations.size());
  } else {
    fragmentDescriptor.language = backend::ShaderModuleDescriptor::Language::SPIRV;
    fragmentDescriptor.code = stored->desc.fragmentSpirv.data();
    fragmentDescriptor.codeSize = stored->desc.fragmentSpirv.size() * sizeof(uint32_t);
  }
  backend::ShaderModuleHandle fragmentModule = backend::ShaderModuleHandle::invalid();
  if (!backend::isSuccess(device->createShaderModule(fragmentDescriptor, &fragmentModule))) {
    mDiagnostics = body ? "the effect's fragment stage did not compile; the composed source is in diagnostics"
                        : "the effect's fragment module did not compile or translate";
    return;
  }
  device->destroyShaderModule(fragmentModule);

  backend::DescriptorSetLayoutDescriptor setLayoutDescriptor;
  setLayoutDescriptor.label = stored->desc.name.c_str();
  setLayoutDescriptor.bindingCount = totalBindings;
  for (uint32_t index = 0; index < totalBindings; ++index) {
    setLayoutDescriptor.bindings[index] = { index, backend::BindingType::TextureSampler, 1,
                                            static_cast<uint8_t>((1u << 0) | (1u << 1)), nullptr };
  }
  if (!backend::isSuccess(device->createDescriptorSetLayout(setLayoutDescriptor, &mSetLayout))) {
    mDiagnostics = "the effect's descriptor set layout could not be created";
    return;
  }

  backend::PipelineLayoutDescriptor pipelineLayoutDescriptor;
  pipelineLayoutDescriptor.setLayoutCount = 1;
  pipelineLayoutDescriptor.setLayouts[0] = mSetLayout;
  pipelineLayoutDescriptor.label = stored->desc.name.c_str();
  if (!backend::isSuccess(device->createPipelineLayout(pipelineLayoutDescriptor, &mPipelineLayout))) {
    mDiagnostics = "the effect's pipeline layout could not be created";
    return;
  }

  mValid = true;
}

RenderProgram::~RenderProgram() { destroyObjects(); }
bool RenderProgram::isDeviceCurrent() const noexcept {
  return mCore.deviceGeneration() == mDeviceGeneration;
}

void RenderProgram::destroyObjects() noexcept {
  if (!isDeviceCurrent()) {
    // The core has replaced its device; these handles belong to the old one and must not be passed
    // to the new device. Clearing the containers is all that is left to do.
    mSets.clear();
    mPipelines.clear();
    mSetLayout = backend::DescriptorSetLayoutHandle::invalid();
    mPipelineLayout = backend::PipelineLayoutHandle::invalid();
    mValid = false;
    return;
  }
  backend::Device* device = mCore.device();
  if (device == nullptr) return;
  for (SetEntry& entry : mSets) {
    if (entry.set.valid()) device->destroyDescriptorSet(entry.set);
  }
  mSets.clear();
  for (PipelineEntry& entry : mPipelines) {
    if (entry.pipeline.valid()) device->destroyRenderPipeline(entry.pipeline);
  }
  mPipelines.clear();
  if (mSetLayout.valid()) device->destroyDescriptorSetLayout(mSetLayout);
  if (mPipelineLayout.valid()) device->destroyPipelineLayout(mPipelineLayout);
  mSetLayout = backend::DescriptorSetLayoutHandle::invalid();
  mPipelineLayout = backend::PipelineLayoutHandle::invalid();
  mValid = false;
}

static constexpr uint32_t kFullTargetVertexStride = 4 * sizeof(float);

bool RenderProgram::makeShaderModuleDescriptors(backend::ShaderModuleDescriptor& vertexDescriptor,
                                                backend::ShaderModuleDescriptor& fragmentDescriptor) const {
  vertexDescriptor = backend::ShaderModuleDescriptor{};
  vertexDescriptor.stage = backend::ShaderStage::Vertex;
  vertexDescriptor.language = mDirectGlsl ? backend::ShaderModuleDescriptor::Language::GLSLDirect
                                          : backend::ShaderModuleDescriptor::Language::GLSL;
  vertexDescriptor.code = mVertexSource.c_str();
  vertexDescriptor.codeSize = mDirectGlsl ? mVertexSource.size() : mVertexSource.size() + 1;
  vertexDescriptor.label = "effect/effect.vert";

  fragmentDescriptor = backend::ShaderModuleDescriptor{};
  fragmentDescriptor.stage = backend::ShaderStage::Fragment;
  fragmentDescriptor.label = "effect/effect.frag";
  if (mSnapshot->desc.authoring == EffectShaderAuthoring::Body) {
    fragmentDescriptor.language = mDirectGlsl ? backend::ShaderModuleDescriptor::Language::GLSLDirect
                                              : backend::ShaderModuleDescriptor::Language::GLSL;
    fragmentDescriptor.code = mFragmentSource.c_str();
    fragmentDescriptor.codeSize = mDirectGlsl ? mFragmentSource.size() : mFragmentSource.size() + 1;
    fragmentDescriptor.bindingDeclarations = mDeclarations.data();
    fragmentDescriptor.bindingDeclarationCount = static_cast<uint32_t>(mDeclarations.size());
  } else {
    fragmentDescriptor.language = backend::ShaderModuleDescriptor::Language::SPIRV;
    fragmentDescriptor.code = mSnapshot->desc.fragmentSpirv.data();
    fragmentDescriptor.codeSize = mSnapshot->desc.fragmentSpirv.size() * sizeof(uint32_t);
  }
  return true;
}

void RenderProgram::fillPipelineDescriptor(const backend::PixelFormat colorFormat,
                                           const backend::RenderPassHandle compatiblePass,
                                           const backend::ShaderModuleHandle vertexModule,
                                           const backend::ShaderModuleHandle fragmentModule,
                                           backend::RenderPipelineDescriptor& descriptor) const {
  descriptor.layout = mPipelineLayout;
  descriptor.vertexModule = vertexModule;
  descriptor.fragmentModule = fragmentModule;
  descriptor.compatibleRenderPass = compatiblePass;
  descriptor.label = mSnapshot->desc.name.c_str();

  descriptor.rasterizer.topology = backend::PrimitiveTopology::TriangleList;
  descriptor.rasterizer.cullMode = backend::CullMode::None;
  descriptor.rasterizer.flipY = false;
  descriptor.depthStencil.depthTestEnable = false;
  descriptor.depthStencil.depthWriteEnable = false;
  descriptor.depthStencil.stencilEnable = false;
  descriptor.multisample.sampleCount = 1;
  descriptor.vertexInput.bufferCount = 1;
  descriptor.vertexInput.buffers[0] = { kFullTargetVertexStride, backend::VertexStepMode::Vertex, 0, 2 };
  descriptor.vertexInput.attributeCount = 2;
  descriptor.vertexInput.attributes[0] = { 0, 0, backend::VertexFormat::Float2, 0 };
  descriptor.vertexInput.attributes[1] = { 1, 0, backend::VertexFormat::Float2, 8 };
  descriptor.colorTargetCount = 1;
  descriptor.colorTargets[0].format = colorFormat;
  // Opaque: a pass writes every pixel of its target, so blending would only composite the result against
  // whatever the pooled target happened to hold.
  descriptor.colorTargets[0].blend = backend::BlendState::opaque();
  descriptor.depthStencilFormat = backend::PixelFormat::Undefined;
}

bool RenderProgram::makePipelineDescriptor(const backend::PixelFormat colorFormat,
                                           const backend::RenderPassHandle compatiblePass,
                                           backend::RenderPipelineDescriptor& descriptor,
                                           backend::ShaderModuleHandle& vertexModule,
                                           backend::ShaderModuleHandle& fragmentModule) {
  backend::Device* device = mCore.device();
  if (device == nullptr || !mPipelineLayout.valid() || !isDeviceCurrent()) return false;
  backend::ShaderModuleDescriptor vertexDescriptor;
  backend::ShaderModuleDescriptor fragmentDescriptor;
  if (!makeShaderModuleDescriptors(vertexDescriptor, fragmentDescriptor)) return false;
  vertexModule = backend::ShaderModuleHandle::invalid();
  if (!backend::isSuccess(device->createShaderModule(vertexDescriptor, &vertexModule))) return false;
  fragmentModule = backend::ShaderModuleHandle::invalid();
  if (!backend::isSuccess(device->createShaderModule(fragmentDescriptor, &fragmentModule))) {
    device->destroyShaderModule(vertexModule);
    vertexModule = backend::ShaderModuleHandle::invalid();
    return false;
  }
  fillPipelineDescriptor(colorFormat, compatiblePass, vertexModule, fragmentModule, descriptor);
  return true;
}
backend::RenderPipelineHandle RenderProgram::createPipeline(const backend::PixelFormat colorFormat,
                                                            const backend::RenderPassHandle compatiblePass) {
  backend::Device* device = mCore.device();
  if (device == nullptr || !isDeviceCurrent()) return backend::RenderPipelineHandle::invalid();
  backend::RenderPipelineDescriptor descriptor;
  backend::ShaderModuleHandle vertexModule = backend::ShaderModuleHandle::invalid();
  backend::ShaderModuleHandle fragmentModule = backend::ShaderModuleHandle::invalid();
  if (!makePipelineDescriptor(colorFormat, compatiblePass, descriptor, vertexModule, fragmentModule)) {
    return backend::RenderPipelineHandle::invalid();
  }
  backend::RenderPipelineHandle pipeline = backend::RenderPipelineHandle::invalid();
  const backend::Result linked = device->createRenderPipeline(descriptor, &pipeline);
  device->destroyShaderModule(vertexModule);
  device->destroyShaderModule(fragmentModule);
  if (!backend::isSuccess(linked)) return backend::RenderPipelineHandle::invalid();
  return pipeline;
}

bool RenderProgram::requestPipelineAsync(const backend::PixelFormat colorFormat,
                                         const backend::RenderPassHandle compatiblePass,
                                         std::function<void(bool)> completion) {
  for (const PipelineEntry& entry : mPipelines) {
    if (entry.colorFormat == colorFormat) {
      completion(true);
      return true;
    }
  }
  backend::Device* device = mCore.device();
  if (device == nullptr || !mValid || !isDeviceCurrent()) {
    completion(false);
    return false;
  }

  backend::ShaderModuleDescriptor vertexDescriptor;
  backend::ShaderModuleDescriptor fragmentDescriptor;
  if (!makeShaderModuleDescriptors(vertexDescriptor, fragmentDescriptor)) {
    completion(false);
    return false;
  }

  ++mPendingPipelines;
  auto finish = [this, completion = std::move(completion)](const bool success) {
    --mPendingPipelines;
    completion(success);
  };

  const bool vertexAccepted = device->createShaderModuleAsync(
          vertexDescriptor,
          [this, device, colorFormat, compatiblePass, fragmentDescriptor, finish](
                  const backend::ShaderModuleHandle vertexModule, const backend::Result vertexResult, std::string) {
            if (!backend::isSuccess(vertexResult) || !vertexModule.valid()) {
              finish(false);
              return;
            }
            const bool fragmentAccepted = device->createShaderModuleAsync(
                    fragmentDescriptor,
                    [this, device, colorFormat, compatiblePass, vertexModule, finish](
                            const backend::ShaderModuleHandle fragmentModule, const backend::Result fragmentResult,
                            std::string) {
                      if (!backend::isSuccess(fragmentResult) || !fragmentModule.valid()) {
                        device->destroyShaderModule(vertexModule);
                        finish(false);
                        return;
                      }
                      backend::RenderPipelineDescriptor descriptor;
                      fillPipelineDescriptor(
                              colorFormat, compatiblePass, vertexModule, fragmentModule, descriptor);
                      const bool pipelineAccepted = device->createRenderPipelineAsync(
                              descriptor,
                              [this, device, colorFormat, vertexModule, fragmentModule, finish](
                                      const backend::RenderPipelineHandle pipeline, const backend::Result result,
                                      std::string) {
                                if (backend::isSuccess(result) && pipeline.valid()) {
                                  mPipelines.push_back(PipelineEntry{ colorFormat, pipeline });
                                }
                                device->destroyShaderModule(vertexModule);
                                device->destroyShaderModule(fragmentModule);
                                finish(backend::isSuccess(result) && pipeline.valid());
                              });
                      if (!pipelineAccepted) {
                        device->destroyShaderModule(vertexModule);
                        device->destroyShaderModule(fragmentModule);
                        finish(false);
                      }
                    });
            if (!fragmentAccepted) {
              device->destroyShaderModule(vertexModule);
              finish(false);
            }
          });
  if (!vertexAccepted) {
    finish(false);
    return false;
  }
  return true;
}
backend::RenderPipelineHandle RenderProgram::pipelineFor(const backend::PixelFormat colorFormat,
                                                         const backend::RenderPassHandle compatiblePass,
                                                         bool* created) {
  if (created != nullptr) *created = false;
  for (const PipelineEntry& entry : mPipelines) {
    if (entry.colorFormat == colorFormat) return entry.pipeline;
  }
  if (!mValid || !isDeviceCurrent()) return backend::RenderPipelineHandle::invalid();
  const auto pipelineBegin = std::chrono::steady_clock::now();
  const backend::RenderPipelineHandle pipeline = createPipeline(colorFormat, compatiblePass);
  mCore.recordPipelineCreation(
      std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - pipelineBegin).count());
  if (!pipeline.valid()) return pipeline;
  mPipelines.push_back(PipelineEntry{ colorFormat, pipeline });
  if (created != nullptr) *created = true;
  return pipeline;
}

backend::DescriptorSetHandle RenderProgram::setFor(const std::vector<backend::TextureHandle>& inputs,
                                                   const backend::TextureHandle params,
                                                   const backend::TextureSamplerHandle sampler,
                                                   const std::vector<backend::TextureHandle>& extraTextures,
                                                   bool* created,
                                                   const std::vector<backend::TextureSamplerHandle>* inputSamplers,
                                                   const std::vector<backend::TextureViewHandle>* extraViews,
                                                   const std::vector<backend::TextureViewHandle>* inputViews) {
  if (created != nullptr) *created = false;
  for (const SetEntry& entry : mSets) {
    if (entry.inputs == inputs && entry.extras == extraTextures) return entry.set;
  }
  backend::Device* device = mCore.device();
  if (device == nullptr || !mSetLayout.valid() || !isDeviceCurrent()) return backend::DescriptorSetHandle::invalid();

  constexpr size_t kMaxSets = 16;
  if (mSets.size() >= kMaxSets) {
    auto oldest = std::min_element(mSets.begin(), mSets.end(),
                                   [](const SetEntry& a, const SetEntry& b) { return a.lastUsed < b.lastUsed; });
    if (oldest != mSets.end()) {
      device->destroyDescriptorSet(oldest->set);
      mSets.erase(oldest);
    }
  }

  backend::DescriptorSetHandle set = backend::DescriptorSetHandle::invalid();
  if (!backend::isSuccess(device->createDescriptorSet(mSetLayout, &set))) return set;

  std::vector<backend::DescriptorWrite> writes;
  writes.reserve(inputs.size() + 1 + extraTextures.size());
  for (size_t index = 0; index < inputs.size(); ++index) {
    backend::DescriptorWrite write;
    write.binding = mSamplerBindings[index];
    write.type = backend::BindingType::TextureSampler;
    write.texture = inputs[index];
    if (inputViews != nullptr && index < inputViews->size()) write.view = (*inputViews)[index];
    write.sampler = inputSamplers != nullptr && index < inputSamplers->size() && (*inputSamplers)[index].valid()
                        ? (*inputSamplers)[index]
                        : sampler;
    writes.push_back(write);
  }
  backend::DescriptorWrite paramsWrite;
  paramsWrite.binding = mParamsBinding;
  paramsWrite.type = backend::BindingType::TextureSampler;
  paramsWrite.texture = params;
  paramsWrite.sampler = sampler;
  writes.push_back(paramsWrite);

  for (size_t index = 0; index < extraTextures.size(); ++index) {
    backend::DescriptorWrite write;
    write.binding = mExtraBinding + static_cast<uint32_t>(index);
    write.type = backend::BindingType::TextureSampler;
    write.texture = extraTextures[index];
    write.sampler = sampler;
    if (extraViews != nullptr && index < extraViews->size()) write.view = (*extraViews)[index];
    writes.push_back(write);
  }

  if (!backend::isSuccess(device->updateDescriptorSet(set, writes.data(), static_cast<uint32_t>(writes.size())))) {
    device->destroyDescriptorSet(set);
    return backend::DescriptorSetHandle::invalid();
  }
  mSets.push_back(SetEntry{ inputs, extraTextures, set, mLastUsed });
  if (created != nullptr) *created = true;
  return set;
}

